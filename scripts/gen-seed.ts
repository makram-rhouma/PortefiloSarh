// Generates supabase/migrations/*_seed.sql from src/content/defaults.ts (run: node scripts/gen-seed.ts)
import { writeFileSync } from 'node:fs'
import * as d from '../src/content/defaults.ts'

const lit = (v: unknown) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`
const rows = (table: string, items: object[], jsonCols: string[]) =>
  items.map((it) => {
    const cols = Object.keys(it)
    const vals = cols.map((c) => (jsonCols.includes(c) ? json((it as Record<string, unknown>)[c]) : lit((it as Record<string, unknown>)[c])))
    return `insert into public.${table} (${cols.join(', ')}) values (${vals.join(', ')}) on conflict do nothing;`
  }).join('\n')

const { siteUrl: _omit, ...general } = d.settings
void _omit
const sql = `-- Seed content (generated by scripts/gen-seed.ts). Never overwrites existing rows.
insert into public.site_settings (key, value) values ('general', ${json({ ...general, siteUrl: d.SITE_URL_FALLBACK })}) on conflict do nothing;
insert into public.site_settings (key, value) values ('translations', '{}'::jsonb) on conflict do nothing;
${Object.entries(d.sections).map(([k, v], i) => `insert into public.portfolio_sections (key, content, sort_order) values (${lit(k)}, ${json(v)}, ${i}) on conflict do nothing;`).join('\n')}
${rows('experiences', d.experiences, ['role', 'company', 'location', 'bullets'])}
${rows('education', d.education, ['title', 'institution'])}
${rows('skills', d.skills, ['name'])}
${rows('languages', d.languages, ['name', 'level'])}
${rows('social_links', d.socials, ['label'])}
${rows('portfolio_items', d.portfolio, ['title', 'description', 'caption'])}
`
writeFileSync(new URL('../supabase/migrations/20261123000002_seed.sql', import.meta.url), sql)
console.log('seed written', sql.length, 'bytes')
